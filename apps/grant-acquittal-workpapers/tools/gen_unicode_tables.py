"""Generate src/tables.rs from the running CPython's Unicode database.

The workpaper's text rules come from CPython: str.strip() uses str.isspace(),
number parsing accepts any decimal digit, repr() escapes characters that
str.isprintable() rejects, and the text checks read the general category.
Run with the newest supported Python, format and commit the output:

    python tools/gen_unicode_tables.py > src/tables.rs
    cargo fmt
"""

import sys
import unicodedata


def runs(value_of):
    """Each maximal run of code points sharing a value, as (low, high, value)."""
    out, start, current = [], 0, value_of(chr(0))
    for cp in range(1, 0x110000):
        value = value_of(chr(cp))
        if value != current:
            out.append((start, cp - 1, current))
            start, current = cp, value
    out.append((start, 0x10FFFF, current))
    return out


def emit_set(name, predicate):
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for low, high, inside in runs(predicate):
        if inside:
            print(f"    (0x{low:04X}, 0x{high:04X}),")
    print("];")
    print()


def decimal_zeros():
    zeros = [cp for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) == 0]
    # pytext.rs assumes every decimal digit sits in a run of ten from its zero.
    digits = set()
    for zero in zeros:
        if [unicodedata.decimal(chr(zero + d), None) for d in range(10)] != list(range(10)):
            raise SystemExit(f"decimal digits do not run 0 to 9 from {zero:#x}")
        digits.update(range(zero, zero + 10))
    if digits != {cp for cp in range(0x110000) if chr(cp).isdecimal()}:
        raise SystemExit("decimal digit runs do not cover every str.isdecimal() code point")
    return zeros


def category_class(ch):
    """C*, Zl, Zp and the first letter of every other category."""
    category = unicodedata.category(ch)
    return category if category in ("Zl", "Zp") else category[0]


print(f"// Generated by tools/gen_unicode_tables.py from Python {sys.version.split()[0]}")
print(f"// (Unicode {unicodedata.unidata_version}). Do not edit by hand.")
print()
emit_set("PY_SPACE", str.isspace)
print("pub const DECIMAL_ZEROS: &[u32] = &[")
print("".join(f"    0x{zero:04X},\n" for zero in decimal_zeros()), end="")
print("];")
print()
emit_set("PY_NOT_PRINTABLE", lambda ch: not ch.isprintable())
print("/// Unicode general category, reduced to its first letter except Zl and Zp.")
print("pub const CATEGORY: &[(u32, u32, &str)] = &[")
for low, high, value in runs(category_class):
    print(f'    (0x{low:04X}, 0x{high:04X}, "{value}"),')
print("];")

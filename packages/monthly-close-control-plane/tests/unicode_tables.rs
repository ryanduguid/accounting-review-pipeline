//! `src/tables.rs` is a copy of the Review Ready Gate's generated tables.

/// Everything after the first line, which names the generator's path.
fn body(text: &'static [u8]) -> &'static [u8] {
    let end = text.iter().position(|&b| b == b'\n').unwrap();
    &text[end + 1..]
}

#[test]
fn the_unicode_tables_match_the_generated_review_ready_gate_tables() {
    let own = include_bytes!("../src/tables.rs");
    let generated = include_bytes!("../../review-ready-gate/src/tables.rs");
    assert!(
        own.starts_with(b"// Generated by packages/review-ready-gate/tools/gen_unicode_tables.rs ")
    );
    assert!(generated.starts_with(b"// Generated by tools/gen_unicode_tables.rs "));
    assert!(body(own) == body(generated));
}

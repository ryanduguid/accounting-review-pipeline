"""Explicit translations of frozen evatt patterns to fancy-regex.

patterns.json records every pattern from evatt 0.2.0 at repository snapshot
efa253847e4ecdca5ae9b4abec045c0b16b6835c, including refusal probes and number classification. Keeping the
Python expression alongside the translation makes order and greediness
reviewable without a sibling dependency or an installed Python at runtime.

    python3.14 tools/gen_patterns.py > src/regexes.rs
"""

import functools
import json
from pathlib import Path
import re
from re import _parser as parser, _constants as c
from gen_unicode_tables import LIMIT, ignorecase_groups, regex_class

SCALARS = set(range(LIMIT)) - set(range(0xD800, 0xE000))
GROUPS = ignorecase_groups()


@functools.cache
def category(kind):
    predicates = {
        c.CATEGORY_WORD: lambda ch: ch.isalnum() or ch == "_",
        c.CATEGORY_DIGIT: str.isdecimal,
        c.CATEGORY_SPACE: str.isspace,
    }
    opposites = {
        c.CATEGORY_NOT_WORD: c.CATEGORY_WORD,
        c.CATEGORY_NOT_DIGIT: c.CATEGORY_DIGIT,
        c.CATEGORY_NOT_SPACE: c.CATEGORY_SPACE,
    }
    if kind in opposites:
        return SCALARS - category(opposites[kind])
    return {cp for cp in SCALARS if predicates[kind](chr(cp))}


def literal(cp, insensitive):
    if cp not in SCALARS:
        return "(?!)"
    return regex_class(GROUPS[cp]) if insensitive and cp in GROUPS else f"\\x{{{cp:X}}}"


def char_class(items, insensitive):
    points = set()
    negate = False
    for op, arg in items:
        if op == c.NEGATE:
            negate = True
        elif op == c.LITERAL:
            points.update(GROUPS.get(arg, (arg,)) if insensitive else (arg,))
        elif op == c.RANGE:
            for cp in range(arg[0], arg[1] + 1):
                points.update(GROUPS.get(cp, (cp,)) if insensitive else (cp,))
        elif op == c.CATEGORY:
            points.update(category(arg))
        else:
            raise ValueError((op, arg))
    return regex_class(SCALARS - points if negate else points)


def anchor(kind):
    word = regex_class(category(c.CATEGORY_WORD))
    return {
        c.AT_BEGINNING_STRING: r"\A",
        c.AT_BEGINNING: r"\A",
        c.AT_END_STRING: r"\z",
        c.AT_END: r"(?=\n?\z)",
        c.AT_BOUNDARY: f"(?:(?<={word})(?!{word})|(?<!{word})(?={word}))",
        c.AT_NON_BOUNDARY: f"(?:(?<={word})(?={word})|(?<!{word})(?!{word}))",
    }[kind]


def translate(parsed, insensitive, names):
    out = []
    for op, arg in parsed:
        if op == c.LITERAL:
            out.append(literal(arg, insensitive))
        elif op == c.IN:
            out.append(char_class(arg, insensitive))
        elif op == c.NOT_LITERAL:
            out.append(char_class([(c.NEGATE, None), (c.LITERAL, arg)], insensitive))
        elif op == c.CATEGORY:
            out.append(regex_class(category(arg)))
        elif op == c.BRANCH:
            out.append(
                "(?:" + "|".join(translate(branch, insensitive, names) for branch in arg[1]) + ")"
            )
        elif op == c.SUBPATTERN:
            group, add, remove, body = arg
            prefix = "(?:" if group is None else f"(?P<{names[group]}>" if group in names else "("
            flag = bool(add & re.I) or insensitive and not remove & re.I
            out.append(prefix + translate(body, flag, names) + ")")
        elif op in (c.MAX_REPEAT, c.MIN_REPEAT, c.POSSESSIVE_REPEAT):
            low, high, body = arg
            suffix = "{" + str(low) + "," + (str(high) if high != c.MAXREPEAT else "") + "}"
            if low == high:
                suffix = "{" + str(low) + "}"
            if op == c.MIN_REPEAT:
                suffix += "?"
            out.append("(?:" + translate(body, insensitive, names) + ")" + suffix)
            if op == c.POSSESSIVE_REPEAT:
                out[-1] = "(?>" + out[-1] + ")"
        elif op in (c.ASSERT, c.ASSERT_NOT):
            direction, body = arg
            prefix = (
                ("(?<=" if direction == -1 else "(?=")
                if op == c.ASSERT
                else ("(?<!" if direction == -1 else "(?!")
            )
            out.append(prefix + translate(body, insensitive, names) + ")")
        elif op == c.AT:
            out.append(anchor(arg))
        elif op == c.ATOMIC_GROUP:
            out.append("(?>" + translate(arg, insensitive, names) + ")")
        elif op == c.GROUPREF:
            out.append("\\g<" + str(arg) + ">")
        else:
            raise ValueError((op, arg))
    return "".join(out)


def generate():
    specs = json.loads(Path(__file__).with_name("patterns.json").read_text())
    print("// Generated by tools/gen_patterns.py from frozen evatt 0.2.0 patterns.")
    print(
        "// Source: evatt/patterns.py and evatt/redact.py at snapshot efa253847e4ecdca5ae9b4abec045c0b16b6835c."
    )
    print("// No Rust Unicode classes or IGNORECASE flags are used. Do not edit.\n")
    expressions = []
    classes = {}

    def intern(match):
        text = match.group()
        if text not in classes:
            classes[text] = f"@C{len(classes)}@"
        return classes[text]

    for name, spec in specs.items():
        parsed = parser.parse(spec["pattern"], re.I if spec["ignorecase"] else 0)
        names = {v: k for k, v in parsed.state.groupdict.items()}
        regex = translate(parsed, spec["ignorecase"], names)
        expressions.append((name, re.sub(r"\[[^\[\]]+\]", intern, regex)))
    print("pub const CLASSES: &[(&str, &str)] = &[")
    for text, key in classes.items():
        print(f'    ("{key}",r###"{text}"###),')
    print("];")
    print("pub const PATTERNS: &[(&str, &str)] = &[")
    for name, regex in expressions:
        if name == "EMAIL":
            print('    #[cfg(any(test, feature = "probe"))]')
        print(f'    ("{name}", r###"{regex}"###),')
    print("];")
    print("pub fn expand(expression: &str) -> String {")
    print(
        "    CLASSES.iter().fold(expression.to_string(), |text, &(key, class)| text.replace(key, class))"
    )
    print("}")
    for name, kind in [("WORD", c.CATEGORY_WORD)]:
        print(f'pub const {name}: &str = r###"{regex_class(category(kind))}"###;')
    # value_pattern's lookahead/capture/backreference joins are replaced with
    # atomic groups at runtime. Keep the translated join atom for that build.
    from_spec = specs["_JOIN_SPLIT"]["pattern"]
    parsed = parser.parse(from_spec, re.I)
    # _JOIN_SPLIT is a single repeat of _JOIN_ATOM.
    atom = parsed[0][1][2]
    print(f'pub const JOIN_ATOM: &str = r###"{translate(atom, True, {})}"###;')


if __name__ == "__main__":
    generate()

"""Generate src/tables.rs from the running CPython's Unicode database.

The gateway's text rules come from CPython: str.strip() and Decimal() use
str.isspace(), Decimal() and the timestamp regex accept any decimal digit
(category Nd), and repr() escapes characters that str.isprintable() rejects.
Run with the newest supported Python and commit the output:

    python tools/gen_unicode_tables.py > src/tables.rs
"""

import sys
import unicodedata


def ranges(predicate):
    out, start = [], None
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, pairs):
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for low, high in pairs:
        print(f"    (0x{low:04X}, 0x{high:04X}),")
    print("];")


print(f"// Generated by tools/gen_unicode_tables.py from Python {sys.version.split()[0]}")
print(f"// (Unicode {unicodedata.unidata_version}). Do not edit by hand.")
print()
emit("PY_SPACE", ranges(str.isspace))
print()
zeros = [cp for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) == 0]
# The tables assume every decimal digit sits in a run of ten from its zero.
for zero in zeros:
    if not all(unicodedata.decimal(chr(zero + d), None) == d for d in range(10)):
        raise SystemExit(f"decimal digits do not run 0 to 9 from {zero:#x}")
digits = {zero + d for zero in zeros for d in range(10)}
if digits != {cp for cp in range(0x110000) if chr(cp).isdecimal()}:
    raise SystemExit("decimal digit runs do not cover every str.isdecimal() code point")
print("pub const DECIMAL_ZEROS: &[u32] = &[")
for zero in zeros:
    print(f"    0x{zero:04X},")
print("];")
print()
emit("PY_NOT_PRINTABLE", ranges(lambda ch: not ch.isprintable()))

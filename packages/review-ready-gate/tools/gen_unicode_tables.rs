//! Freeze the CPython Unicode rules used by the readiness gate. Python is needed only
//! as the original behaviour oracle when regenerating, never by the binaries.
//! Build: rustc --edition 2024 tools/gen_unicode_tables.rs -o gen-unicode-tables
//! Run: gen-unicode-tables <CPython-3.15-executable> <src/tables.rs>
use std::{env, fs, process::Command};

const CAPTURE: &str = r#"
import sys, unicodedata
if sys.version_info[:2] != (3, 15) or unicodedata.unidata_version != '17.0.0':
    raise SystemExit('requires CPython 3.15 with Unicode 17.0.0')
print('// Generated by tools/gen_unicode_tables.rs from CPython ' + sys.version.split()[0])
print('// Unicode ' + unicodedata.unidata_version + '; do not edit by hand.\n')
def ranges(name, predicate):
    print('pub const ' + name + ': &[(u32, u32)] = &[')
    start = None
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if start is None: start = cp
        elif start is not None:
            print(f'    (0x{start:X}, 0x{cp-1:X}),')
            start = None
    if start is not None: print(f'    (0x{start:X}, 0x10FFFF),')
    print('];\n')
ranges('PY_SPACE', str.isspace)
ranges('PY_NOT_PRINTABLE', lambda ch: not ch.isprintable())
ranges('PY_CONTROL_FORMAT', lambda ch: unicodedata.category(ch) in {'Cc', 'Cf', 'Cs'})
ranges('PY_CASED', lambda ch: ch.islower() or ch.isupper() or ch.istitle())
ranges('PY_CASE_IGNORABLE', lambda ch: ('AΣ' + ch + 'A').lower()[1] == 'σ' and ('AΣ' + ch).lower()[1] == 'ς')
print('pub const DECIMAL_ZEROS: &[u32] = &[')
for cp in range(0x110000):
    if unicodedata.decimal(chr(cp), None) == 0: print(f'    0x{cp:X},')
print('];\n')
for name, transform in [('PY_LOWER', str.lower), ('PY_CASEFOLD', str.casefold)]:
    print('pub const ' + name + ': &[(u32, &str)] = &[')
    for cp in range(0x110000):
        mapped = transform(chr(cp))
        if mapped != chr(cp):
            escaped = ''.join('\\u{' + f'{ord(ch):X}' + '}' for ch in mapped)
            print(f'    (0x{cp:X}, "{escaped}"),')
    print('];\n')
"#;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<_> = env::args_os().skip(1).collect();
    if args.len() != 2 { return Err("usage: gen-unicode-tables CPYTHON OUTPUT".into()); }
    let captured = Command::new(&args[0]).args(["-I", "-c", CAPTURE]).output()?;
    if !captured.status.success() { return Err(String::from_utf8_lossy(&captured.stderr).into_owned().into()); }
    let text = String::from_utf8(captured.stdout)?.replace("\r\n", "\n");
    fs::write(&args[1], text)?;
    Ok(())
}
